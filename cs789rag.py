def graphrag_project(root: str | Path, entity_types: list | None = None,
                     docs: Sequence[Document] | None = None, extra_files: Sequence[str] = ()) -> Path:
    """Create (or refresh) a Microsoft GraphRAG project folder wired to the local vLLM servers.

    root/input/          one .md per corpus document
    root/settings.yaml   from graphrag_settings.yaml with the entity types filled in
    root/prompts/        the default prompts written by `graphrag init`
    """
    root = Path(root)
    if not (root / "prompts").exists():
        subprocess.run(f"graphrag init --root {root} --force -m llm -e emb", shell=True, check=True,
                       capture_output=True)
    (root / "input").mkdir(parents=True, exist_ok=True)
    for d in (docs or load_corpus()):
        Path(root / "input" / Path(d.path).name).write_text(Path(d.path).read_text())
    for f in extra_files:
        Path(root / "input" / Path(f).name).write_text(Path(f).read_text())
    types = entity_types or SECURITY_ENTITY_TYPES
    tpl = (HERE / "graphrag_settings.yaml").read_text()
    (root / "settings.yaml").write_text(tpl.replace("{ENTITY_TYPES}", "[" + ",".join(types) + "]"))
    (root / ".env").write_text("GRAPHRAG_API_KEY=EMPTY\n")
    print(f"GraphRAG project ready at {root}: {len(list((root / 'input').glob('*.md')))} input files, "
          f"entity types = {types}")
    return root


def graphrag_index(root: str | Path, method: str = "standard") -> dict:
    """Run `graphrag index` (standard | fast) or `graphrag update` (standard-update | fast-update); time it."""
    root = Path(root)
    t = time.time()
    logf = root / f"index_{method}.log"
    with open(logf, "w") as fh:
        # GraphRAG 3.x: incremental updates are their own command, `graphrag update --method standard|fast`
        cmd = (f"graphrag update --root {root} --method {method[:-len('-update')]}" if method.endswith("-update")
               else f"graphrag index --root {root} --method {method}")
        p = subprocess.Popen(cmd, shell=True,
                             stdout=fh, stderr=subprocess.STDOUT, text=True)
        last = ""
        while p.poll() is None:            # show progress from GraphRAG's own log every 20 s
            time.sleep(20)
            eng = root / "logs" / "indexing-engine.log"
            if eng.exists():
                prog = [ln for ln in eng.read_text(errors="replace").splitlines() if "progress" in ln]
                if prog and prog[-1] != last:
                    last = prog[-1]
                    print(f"  [{time.time() - t:5.0f}s] {last.split(' - ')[-1][:100]}", flush=True)
    sec = round(time.time() - t, 1)
    tail = logf.read_text(errors="replace")[-2500:]
    if p.returncode != 0:
        print(tail)
        raise RuntimeError("graphrag index failed -- see the output above and root/logs/")
    stats = {}
    sp = root / "output" / "stats.json"
    if sp.exists():
        stats = json.loads(sp.read_text())
    print(f"{cmd.split(' --root')[0]} --method {method}: {sec} s")
    _GR_CACHE.pop(str(root), None)
    return {"seconds": sec, "stats": stats}


_GR_CACHE: dict = {}


def graphrag_tables(root: str | Path) -> dict:
    """The index as pandas DataFrames: entities, relationships, communities, community_reports, text_units."""
    import pandas as pd
    out = Path(root) / "output"
    names = ["entities", "relationships", "communities", "community_reports", "text_units", "documents"]
    return {n: pd.read_parquet(out / f"{n}.parquet") for n in names if (out / f"{n}.parquet").exists()}


def graphrag_ask(root: str | Path, method: str, question: str, community_level: int = 2,
                 response_type: str = "A short paragraph") -> str:
    """Ask the GraphRAG index a question. method: local | global | drift | basic."""
    import graphrag.api as api
    from graphrag.config.load_config import load_config
    key = str(root)
    if key not in _GR_CACHE:
        cfg = load_config(root_dir=Path(root))
        _GR_CACHE[key] = (cfg, graphrag_tables(root))
    cfg, T = _GR_CACHE[key]
    if method == "local":
        coro = api.local_search(config=cfg, entities=T["entities"], communities=T["communities"],
                                community_reports=T["community_reports"], text_units=T["text_units"],
                                relationships=T["relationships"], covariates=None,
                                community_level=community_level, response_type=response_type, query=question)
    elif method == "global":
        coro = api.global_search(config=cfg, entities=T["entities"], communities=T["communities"],
                                 community_reports=T["community_reports"], community_level=community_level,
                                 dynamic_community_selection=False, response_type=response_type, query=question)
    elif method == "drift":
        coro = api.drift_search(config=cfg, entities=T["entities"], communities=T["communities"],
                                community_reports=T["community_reports"], text_units=T["text_units"],
                                relationships=T["relationships"], community_level=community_level,
                                response_type=response_type, query=question)
    elif method == "basic":
        coro = api.basic_search(config=cfg, text_units=T["text_units"], response_type=response_type,
                                query=question)
    else:
        raise ValueError("method must be local, global, drift or basic")
    response, _context = run_async(coro)
    return response if isinstance(response, str) else json.dumps(response)[:2000]
