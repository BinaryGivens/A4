def install_vllm(env: str = VLLM_ENV):
    """Install vLLM into its OWN virtualenv so it cannot break the notebook's torch."""
    if Path(env, "bin", "vllm").exists():
        print("vLLM already installed in", env)
        return
    t = time.time()
    subprocess.run(f"CS789_VLLM_ENV={env} bash {HERE / 'install_vllm.sh'}", shell=True, check=True)
    print(f"vLLM installed in {time.time() - t:.0f}s")


_PROCS: dict = {}          # port -> subprocess.Popen


def _log_path(port: int) -> str:
    return VLLM_LOG.replace(".log", f"_{port}.log")


def _start_server(cmd: str, port: int, timeout: int, what: str):
    stop_vllm(port)
    log = open(_log_path(port), "w")
    t = time.time()
    env = dict(os.environ)
    # the venv's bin must come first: FlashInfer JIT-compiles kernels with the venv's `ninja`
    env["PATH"] = f"{VLLM_ENV}/bin:/usr/local/cuda/bin:" + env.get("PATH", "")
    env["VIRTUAL_ENV"] = VLLM_ENV
    proc = subprocess.Popen(cmd, shell=True, stdout=log, stderr=subprocess.STDOUT, preexec_fn=os.setsid,
                            env=env)
    _PROCS[port] = proc
    import requests
    while time.time() - t < timeout:
        if proc.poll() is not None:
            print(Path(_log_path(port)).read_text()[-3000:])
            raise RuntimeError(f"vLLM ({what}) exited while starting -- see the log above")
        try:
            if requests.get(f"http://localhost:{port}/v1/models", timeout=2).ok:
                return round(time.time() - t)
        except Exception:
            pass
        time.sleep(5)
    raise TimeoutError(f"vLLM ({what}) did not come up; see {_log_path(port)}")


def start_vllm(kv_cache_dtype: str = "auto", model: str = DEFAULT_MODEL,
               max_model_len: int = 49152, gpu_mem: float = 0.85, port: int = VLLM_PORT,
               extra: str = "", timeout: int = 1500) -> dict:
    """(Re)start the vLLM chat server (OpenAI API on localhost:port, model name "llm").

    kv_cache_dtype: auto (bf16), fp8, turboquant_k8v4, turboquant_4bit_nc,
                    turboquant_k3v4_nc, turboquant_3bit_nc
    Returns {"kv_cache_dtype", "kv_tokens", "kv_gib", "max_concurrency", "load_sec"}.
    """
    cmd = (f"{VLLM_ENV}/bin/vllm serve {model} --served-model-name llm --port {port} "
           f"--max-model-len {max_model_len} --gpu-memory-utilization {gpu_mem} "
           f"--kv-cache-dtype {kv_cache_dtype} --enable-prefix-caching {extra}")
    sec = _start_server(cmd, port, timeout, f"chat, kv_cache_dtype={kv_cache_dtype}")
    info = kv_info(port)
    info.update({"kv_cache_dtype": kv_cache_dtype, "load_sec": sec})
    print(f"vLLM up in {sec}s | model={model} | kv_cache_dtype={kv_cache_dtype} | "
          f"KV cache = {info.get('kv_tokens')} tokens ({info.get('kv_gib')} GiB) | "
          f"max concurrency at {max_model_len} tokens = {info.get('max_concurrency')}x")
    return info


def start_embedder(model: str = "BAAI/bge-base-en-v1.5", port: int = 8001, gpu_mem: float = 0.10,
                   timeout: int = 900) -> int:
    """Start a second vLLM server that serves embeddings (OpenAI /v1/embeddings, model name "emb")."""
    cmd = (f"{VLLM_ENV}/bin/vllm serve {model} --served-model-name emb --port {port} "
           f"--runner pooling --gpu-memory-utilization {gpu_mem} --max-model-len 512")
    sec = _start_server(cmd, port, timeout, "embeddings")
    print(f"embedding server up in {sec}s | model={model} | port {port}")
    return sec


def embed(texts: list, port: int = 8001, batch: int = 64):
    """Embed texts with the embedding server; returns a normalized float32 numpy matrix."""
    import numpy as np
    import requests
    out = []
    for i in range(0, len(texts), batch):
        r = requests.post(f"http://localhost:{port}/v1/embeddings", timeout=300,
                          json={"model": "emb", "input": list(texts[i:i + batch]),
                                "truncate_prompt_tokens": 510})   # bge-base reads 512 word-pieces
        r.raise_for_status()
        out += [d["embedding"] for d in sorted(r.json()["data"], key=lambda d: d["index"])]
    E = np.asarray(out, dtype="float32")
    return E / np.linalg.norm(E, axis=1, keepdims=True)


def kv_info(port: int = VLLM_PORT) -> dict:
    """Parse the KV-cache capacity lines out of the vLLM log."""
    lp = Path(_log_path(port))
    txt = lp.read_text() if lp.exists() else ""
    tok = re.findall(r"KV cache size:\s*([\d,]+)\s*tokens", txt)
    conc = re.findall(r"Maximum concurrency for [\d,]+ tokens per request:\s*([\d.]+)x", txt)
    mem = re.findall(r"Available KV cache memory:\s*([\d.]+)\s*GiB", txt)
    return {"kv_tokens": int(tok[-1].replace(",", "")) if tok else None,
            "max_concurrency": float(conc[-1]) if conc else None,
            "kv_gib": float(mem[-1]) if mem else None}


def server_up(port: int = VLLM_PORT) -> bool:
    """True if an OpenAI-compatible server already answers on this port (e.g. after a kernel restart)."""
    import requests
    try:
        return requests.get(f"http://localhost:{port}/v1/models", timeout=2).ok
    except Exception:
        return False


def stop_vllm(port: int = VLLM_PORT):
    """Stop the vLLM server on one port (the chat server by default)."""
    import signal
    proc = _PROCS.pop(port, None)
    if proc is not None and proc.poll() is None:
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
            proc.wait(60)
        except Exception:
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
            except Exception:
                pass
    subprocess.run(f"pkill -f 'vllm serve.*--port {port}( |$)' || true", shell=True)
    time.sleep(3)


def llm(prompt: str | list, system: str | None = None, max_tokens: int = 400,
        temperature: float = 0.0) -> str:
    """Ask the local model one question (OpenAI chat API on localhost:8000)."""
    import requests
    msgs = prompt if isinstance(prompt, list) else (
        ([{"role": "system", "content": system}] if system else []) +
        [{"role": "user", "content": prompt}])
    r = requests.post(f"http://localhost:{VLLM_PORT}/v1/chat/completions", timeout=600,
                      json={"model": "llm", "messages": msgs, "max_tokens": max_tokens,
                            "temperature": temperature})
    r.raise_for_status()
    return r.json()["choices"][0]["message"]["content"]


def count_tokens(text: str, model: str = DEFAULT_MODEL) -> int:
    """Exact token count with the served model's tokenizer."""
    from transformers import AutoTokenizer
    return len(AutoTokenizer.from_pretrained(model).encode(text))


