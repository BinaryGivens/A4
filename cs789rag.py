# ============================================================== async helper (Jupyter)

def run_async(coro):
    """Run a coroutine to completion from a notebook cell (which already has an event loop)."""
    import asyncio
    import threading
    box = {}

    def _runner():
        try:
            box["result"] = asyncio.run(coro)
        except BaseException as e:  # pragma: no cover
            box["error"] = e
    t = threading.Thread(target=_runner)
    t.start()
    t.join()
    if "error" in box:
        raise box["error"]
    return box.get("result")


